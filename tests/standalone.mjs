import { chromium } from 'playwright';
const P = '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const browser = await chromium.launch({ executablePath: P, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
const logs = [];
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
page.on('requestfailed', (r) => logs.push(`[reqfail] ${r.url().slice(0, 120)}`));
await page.addInitScript((m) => { localStorage.setItem('toybox-mayhem.settings.v1', JSON.stringify({ quality: 'low', map: m })); }, process.env.MAP || 'bedroom');
page.setDefaultTimeout(300000);
await page.goto('file://' + process.cwd() + '/standalone/ToyboxMayhem.html');
await page.waitForFunction(() => window.__ready === true, null, { timeout: 300000 });
const r = await page.evaluate(() => { window.__autotest = true; const g = window.__toybox; g.startMatch('normal', 'takeover'); g.debugStep(20); return { state: g.state, kills: g.actors.reduce((s, a) => s + a.kills, 0), fonts: document.fonts.check('20px "Luckiest Guy"') }; });
console.log(JSON.stringify(r));
await page.screenshot({ path: '/tmp/claude-0/shots/standalone.png' });
console.log(logs.join('\n') || 'no errors');
await browser.close();
