import { chromium } from 'playwright';
const P = '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: P, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.addInitScript(() => { window.AudioContext = undefined; try { const s = JSON.parse(localStorage.getItem('toybox-mayhem.settings.v1') || '{}'); s.quality = 'low'; localStorage.setItem('toybox-mayhem.settings.v1', JSON.stringify(s)); } catch {} });
page.setDefaultTimeout(300000);
await page.goto(process.env.URL || 'http://localhost:5173/');
await page.waitForFunction(() => window.__ready === true, null, { timeout: 300000 });
const g = () => page.evaluate(() => { const m = window.__toybox.menus; return !!m; });
console.log('menus', await g());
await page.evaluate(() => window.__toybox.menus.play());
await page.waitForTimeout(1500); await page.screenshot({ path: out + '/menu-play.png' });
await page.evaluate(() => window.__toybox.menus.collection('play'));
await page.waitForTimeout(2500); await page.screenshot({ path: out + '/menu-loadout.png' });
const chips = await page.evaluate(() => [...document.querySelectorAll('button')].map((b) => b.textContent.trim().slice(0, 30)));
console.log(JSON.stringify(chips));
await browser.close();
